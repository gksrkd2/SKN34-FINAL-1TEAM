def policy_of(text: str) -> list[PolicyFlag]:
    return [k for k, p in FLAGS.items() if p.search(text or "")]  # type: ignore[misc]


def out_of_scope(text: str, has_trade: bool = False) -> bool:
    """has_trade: 질문에 공종 낱말이 있음. 그러면 OUT_SOFT 말(집값 · 소품 …)은 범위 밖으로 보지 않아요."""
    t = text or ""
    return bool(OUT_RULES.search(t)) or (not has_trade and bool(OUT_SOFT.search(t)))


def calc_request(text: str) -> bool:
    return bool(CALC_REQUEST.search(text or ""))
